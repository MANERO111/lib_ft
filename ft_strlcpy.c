#include "libft.h"

size_t	ft_strlcpy(char *dst, const char *src, size_t size)
{
	size_t	srcl ;
	size_t	i;

	i = 0;
	srcl = 0;
	while (src[srcl])
		srcl++;
	if (size == 0)
		return (srcl);
	while (i < size -1 && src[i])
	{
		dst[i] = src[i];
		i++;
	}
	dst[i] = '\0';
	return (srcl);
}
